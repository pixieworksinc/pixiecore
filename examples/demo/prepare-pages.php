<?php

/**
 * @file
 * Generates Drupal demo page fragments and libraries from canonical examples.
 */

declare(strict_types=1);

$source = dirname(__DIR__, 2);
$destination = $argv[1] ?? $source . '/examples/integrations/drupal/pixiecore_specification';
if (!is_dir($destination) || !is_file($destination . '/pixiecore_specification.info.yml')) {
  throw new RuntimeException('Expected the existing pixiecore_specification module directory.');
}

/**
 * Reads a trusted repository HTML source, without resolving external resources.
 */
function demo_page_document(string $path): DOMDocument {
  $html = file_get_contents($path);
  if ($html === FALSE) {
    throw new RuntimeException('Cannot read demo page source.');
  }
  $document = new DOMDocument();
  $previous = libxml_use_internal_errors(TRUE);
  $loaded = $document->loadHTML('<?xml encoding="utf-8" ?>' . $html, LIBXML_NONET);
  libxml_clear_errors();
  libxml_use_internal_errors($previous);
  if (!$loaded) {
    throw new RuntimeException('Cannot parse demo page source.');
  }
  return $document;
}

/**
 * Writes literal HTML without allowing repository text to become Twig code.
 */
function demo_page_template(string $path, string $html): void {
  if (preg_match('/\{%[-~]?\s*endverbatim\b/i', $html)) {
    throw new RuntimeException('Demo HTML must not contain a Twig verbatim terminator.');
  }
  if (file_put_contents($path, "{# Generated by examples/demo/prepare-pages.php. #}\n{% verbatim %}" . $html . "{% endverbatim %}\n") === FALSE) {
    throw new RuntimeException('Cannot write generated demo template.');
  }
}

/**
 * Leaves the page's main landmark to the surrounding Drupal theme.
 */
function demo_page_fragment(DOMDocument $document, DOMNode $node): string {
  $html = $document->saveHTML($node);
  return preg_replace(['/<main\b/i', '@</main>@i'], ['<div', '</div>'], $html);
}

foreach (['templates', 'assets/pages', 'assets/replay', 'assets/live'] as $directory) {
  $path = $destination . '/' . $directory;
  if (!is_dir($path) && !mkdir($path, 0755, TRUE) && !is_dir($path)) {
    throw new RuntimeException('Cannot create generated demo directory.');
  }
}
$landing = demo_page_document($source . '/examples/demo/public/index.html');
$main = $landing->getElementsByTagName('main')->item(0);
$style = $landing->getElementsByTagName('style')->item(0);
if (!$main || !$style || $landing->getElementsByTagName('script')->length !== 0) {
  throw new RuntimeException('Landing must contain a main fragment, styles, and no scripts.');
}
demo_page_template($destination . '/templates/pixiecore-demo-landing.html.twig', demo_page_fragment($landing, $main));
if (file_put_contents($destination . '/assets/pages/landing.css', $style->textContent) === FALSE) {
  throw new RuntimeException('Cannot write generated landing styles.');
}
$replay_source = $source . '/examples/pixieagent/demo/replay/public';
$replay = demo_page_document($replay_source . '/index.html');
$body = $replay->getElementsByTagName('body')->item(0);
if (!$body || $replay->getElementsByTagName('script')->length !== 2) {
  throw new RuntimeException('Expected the canonical replay body and two library scripts.');
}
$fragment = '<div class="pixieagent-demo">';
foreach ($body->childNodes as $child) {
  if ($child instanceof DOMElement && in_array($child->tagName, ['script', 'style'], TRUE)) {
    throw new RuntimeException('Replay body must not embed scripts or styles.');
  }
  $fragment .= demo_page_fragment($replay, $child);
}
$fragment .= '</div>';
demo_page_template($destination . '/templates/pixiecore-demo-replay.html.twig', $fragment);
foreach (['style.css', 'data.js', 'app.js'] as $asset) {
  if (!copy($replay_source . '/' . $asset, $destination . '/assets/replay/' . $asset)) {
    throw new RuntimeException('Cannot copy canonical replay library assets.');
  }
}

$live_source = $source . '/examples/pixieagent/demo/live/public';
$live = demo_page_document($live_source . '/index.html');
$body = $live->getElementsByTagName('body')->item(0);
if (!$body || $live->getElementsByTagName('script')->length !== 1) {
  throw new RuntimeException('Expected the canonical live body and its library script.');
}
// The primary route can now render live mode, so retain a distinct replay link.
foreach ($body->getElementsByTagName('a') as $link) {
  if ($link->getAttribute('href') === '/pixieagent/') {
    $link->setAttribute('href', '/pixieagent/replay/');
  }
}
$fragment = '<div class="pixieagent-demo">';
foreach ($body->childNodes as $child) {
  if ($child instanceof DOMElement && in_array($child->tagName, ['script', 'style'], TRUE)) {
    throw new RuntimeException('Live body must not embed scripts or styles.');
  }
  $fragment .= demo_page_fragment($live, $child);
}
$fragment .= '</div>';
demo_page_template($destination . '/templates/pixiecore-demo-live.html.twig', $fragment);
foreach (['style.css', 'app.js'] as $asset) {
  if (!copy($live_source . '/' . $asset, $destination . '/assets/live/' . $asset)) {
    throw new RuntimeException('Cannot copy canonical live library assets.');
  }
}
